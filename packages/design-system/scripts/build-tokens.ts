/**
 * Token pipeline: DTCG JSON -> CSS custom properties + a flat JSON catalogue.
 *
 * - Primitives and semantic tokens are emitted on `:root, [data-tenant]` so that
 *   semantic `var()` references re-resolve inside every tenant scope.
 * - Tenants only override what differs; the cascade does the rest.
 * - The JSON catalogue feeds Storybook docs and the design-system MCP server.
 *
 * In production this would be Style Dictionary fed from Figma variables; the
 * shape of the output is the same.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Json = { [key: string]: unknown };
interface FlatToken {
  path: string[];
  value: string;
  type: string | undefined;
  description: string | undefined;
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src/generated');

const readJson = (file: string): Json => JSON.parse(readFileSync(file, 'utf8')) as Json;

function flatten(node: Json, path: string[] = [], inheritedType?: string): FlatToken[] {
  const type = (node.$type as string | undefined) ?? inheritedType;
  if ('$value' in node) {
    return [{ path, value: String(node.$value), type, description: node.$description as string | undefined }];
  }
  return Object.entries(node)
    .filter(([key]) => !key.startsWith('$'))
    .flatMap(([key, child]) => flatten(child as Json, [...path, key], type));
}

const cssVar = (path: string[]) => `--vds-${path.filter((p) => p !== 'primitive').join('-')}`;
const isPrimitive = (path: string[]) => path[0] === 'primitive';
const aliasPattern = /^\{([^}]+)\}$/;

/** Semantic tokens keep their alias as a CSS var() so tenants can re-point them. */
function toCssValue(token: FlatToken): string {
  const alias = aliasPattern.exec(token.value);
  return alias ? `var(${cssVar(alias[1]!.split('.'))})` : token.value;
}

function resolve(token: FlatToken, byPath: Map<string, FlatToken>, seen = new Set<string>()): string {
  const alias = aliasPattern.exec(token.value);
  if (!alias) return token.value;
  const key = alias[1]!;
  if (seen.has(key)) throw new Error(`Circular token alias at ${key}`);
  const target = byPath.get(key);
  if (!target) throw new Error(`Unknown token alias {${key}} in ${token.path.join('.')}`);
  return resolve(target, byPath, new Set([...seen, key]));
}

const base = flatten(readJson(join(root, 'tokens/base.tokens.json')));
const baseByPath = new Map(base.map((t) => [t.path.join('.'), t]));

const seenVars = new Map<string, string>();
for (const t of base) {
  const name = cssVar(t.path);
  const clash = seenVars.get(name);
  if (clash) throw new Error(`Tokens ${clash} and ${t.path.join('.')} both map to ${name}`);
  seenVars.set(name, t.path.join('.'));
}

const tenantFiles = readdirSync(join(root, 'tokens/tenants')).filter((f) => f.endsWith('.tokens.json'));
const tenants = tenantFiles.map((file) => {
  const json = readJson(join(root, 'tokens/tenants', file));
  const meta = json.$tenant as { id: string; name: string };
  const overrides = flatten(json);
  for (const o of overrides) {
    if (!baseByPath.has(o.path.join('.'))) {
      throw new Error(`Tenant "${meta.id}" overrides unknown token ${o.path.join('.')}`);
    }
  }
  return { ...meta, overrides };
});

const declarations = (tokens: FlatToken[]) =>
  tokens.map((t) => `  ${cssVar(t.path)}: ${toCssValue(t)};`).join('\n');

const css = [
  '/* Generated by scripts/build-tokens.ts. Do not edit by hand. */',
  `:root,\n[data-tenant] {\n${declarations(base)}\n}`,
  ...tenants
    .filter((t) => t.overrides.length > 0)
    .map((t) => `[data-tenant='${t.id}'] {\n${declarations(t.overrides)}\n}`),
  '',
].join('\n\n');

const catalogue = {
  tenants: tenants.map(({ id, name }) => ({ id, name })),
  tokens: base
    .filter((t) => !isPrimitive(t.path))
    .map((t) => {
      const byTenant: Record<string, string> = {};
      for (const tenant of tenants) {
        const merged = new Map(baseByPath);
        for (const o of tenant.overrides) merged.set(o.path.join('.'), o);
        byTenant[tenant.id] = resolve(merged.get(t.path.join('.'))!, merged);
      }
      return {
        name: t.path.join('.'),
        cssVar: cssVar(t.path),
        type: t.type,
        description: t.description,
        aliasOf: aliasPattern.exec(t.value)?.[1],
        valueByTenant: byTenant,
      };
    }),
};

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'tokens.css'), css);
writeFileSync(join(outDir, 'tokens.json'), JSON.stringify(catalogue, null, 2));
writeFileSync(
  join(outDir, 'tenants.ts'),
  [
    '// Generated by scripts/build-tokens.ts. Do not edit by hand.',
    `export const TENANTS = ${JSON.stringify(catalogue.tenants, null, 2)} as const;`,
    "export type TenantId = (typeof TENANTS)[number]['id'];",
    '',
  ].join('\n'),
);
console.log(`tokens: ${base.length} base, ${tenants.length} tenants -> src/generated/tokens.css`);
